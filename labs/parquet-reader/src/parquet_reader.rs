/// writer streams data and cannot know the offsets until it is finished, so
/// a reader seeks to the end first. In order:
///
/// ```text
///   1. the file must be at least MIN_FILE_LEN bytes            → TooShort
///   2. bytes [0, 4) must equal MAGIC                            → BadMagic
///   3. bytes [len-4, len) are footer_len : u32 LE
