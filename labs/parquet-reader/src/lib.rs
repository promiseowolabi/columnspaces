//! parquet-reader — forge lab 04 (columnspaces).
//!
//! A footer parser and column-chunk reader over KSPQ: a small,
//! Parquet-SHAPED teaching format that this harness defines, writes and
//! reads. **It is not Parquet.** The format spec, and the list of what real
//! Parquet has that KSPQ deliberately omits (Thrift metadata, pages,
//! definition/repetition levels, codecs, several physical types, a schema
//! tree, column/offset indexes, the trailing magic), is in the header of
//! `src/parquet_reader.rs`. The course does not overclaim: what this lab
//! teaches is the SHAPE — metadata at the end, byte ranges per column
//! chunk, projection as arithmetic, and refusing malformed input.
//!
//! ┌──────────────────────────────────────────────────────────────────────┐
//! │  YOU EDIT:   src/parquet_reader.rs  (the only file with TODO(you))   │
//! │  DO NOT EDIT this file — it is the grading harness.                   │
//! └──────────────────────────────────────────────────────────────────────┘
//!
//! What the harness is:
//!
//!   * a WRITER that generates files deterministically and keeps a ledger:
//!     the exact byte range of every column chunk, and the exact values it
//!     encoded there. Expectations come from the ledger, not from the
//!     student's parser;
//!   * a second, independent READER, used by `storm` — and audited against
//!     the ledger on every fixture, failing with "HARNESS BUG" if the two
//!     disagree;
//!   * an INSTRUMENTED `Source` that records every `(offset, len)` the
//!     student requests. `projection_reads_minimum` is graded from that
//!     recording as a COUNT of bytes and ranges — never a time. The
//!     assertion is not "fewer bytes than the whole file": it is ZERO bytes
//!     of any chunk the projection did not name.
//!
//! BTreeMap only, never HashMap: std's HashMap seeds itself from OS
//! randomness that does not exist on `wasm32-unknown-unknown`.

