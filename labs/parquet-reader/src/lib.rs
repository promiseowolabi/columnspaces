/// 1. footer_parse: the magic, the footer length at the end of the file,
///    and the schema — read from files the harness wrote, and compared
///    against the writer's ledger rather than against a second parse.
pub fn check_footer_parse() -> Check {
    const ID: &str = "footer_parse";
    const LABEL: &str = "magic, footer length and schema parsed from a generated fixture";
    let mut rng = Rng(0x04F0_07E5);

    let mut fixtures: Vec<Fixture> = edge_fixtures();
    for i in 0..12 {
        fixtures.push(make_fixture(&mut rng, i));
    }

    let mut cols_seen = 0usize;
    let mut files = 0usize;
    for fx in &fixtures {
        if let Err(msg) = audit(fx) {
            return Check::fail(ID, LABEL, msg);
        }
        let rec = Recording::new(&fx.bytes);
        let meta = match parquet_reader::read_footer(&rec) {
            Ok(m) => m,
            Err(e) => {
                return Check::fail(ID, LABEL, format!(
                    "{}: read_footer refused a VALID {}-byte file with {e:?}. The footer is the last {} bytes before the 4-byte length field, which holds {}. (KSPQ is the Parquet-shaped teaching format documented in your file's header — magic at the front, footer length as the final four bytes.)",
                    fx.name, fx.bytes.len(),
                    fx.bytes.len() as u64 - 4 - fx.footer_start,
                    fx.bytes.len() as u64 - 4 - fx.footer_start));
            }
        };
        if meta.version != fx.meta.version {
            return Check::fail(ID, LABEL, format!(
                "{}: version {} , want {} — it is the first u16 of the footer",
                fx.name, meta.version, fx.meta.version));
        }
        if meta.num_rows != fx.meta.num_rows {
            return Check::fail(ID, LABEL, format!(
                "{}: num_rows {}, want {} — a u64 immediately after the version, and the number that answers SELECT count(*) with no data read at all",
                fx.name, meta.num_rows, fx.meta.num_rows));
        }
        if meta.schema.len() != fx.meta.schema.len() {
            return Check::fail(ID, LABEL, format!(
                "{}: {} columns in the schema, want {} — num_columns is a u16, and each column is a u8 length, that many name bytes, then a one-byte logical type tag",
                fx.name, meta.schema.len(), fx.meta.schema.len()));
        }
        for (c, (got, want)) in meta.schema.iter().zip(&fx.meta.schema).enumerate() {
            if got.name != want.name {
                return Check::fail(ID, LABEL, format!(
                    "{}: column {c} is named {:?}, want {:?} — the name is length-prefixed and NOT null-terminated, so a trailing byte here means the type tag was read from inside the name",
                    fx.name, got.name, want.name));
            }
            if got.logical != want.logical {
                return Check::fail(ID, LABEL, format!(
                    "{}: column {c} ({}) has logical type {:?}, want {:?} — 1 = Int64, 2 = Timestamp, 3 = Bool",
                    fx.name, want.name, got.logical, want.logical));
            }
            cols_seen += 1;
        }
        if meta.row_groups.len() != fx.meta.row_groups.len() {
            return Check::fail(ID, LABEL, format!(
                "{}: {} row groups, want {}",
                fx.name, meta.row_groups.len(), fx.meta.row_groups.len()));
        }
        // reading the footer must not read the data region: the whole
        // premise of "seek to the end" is that you learn the shape of the
        // file without touching its contents
        let stray = stray_bytes(&rec, fx, &[]);
        if stray > 0 {
            return Check::fail(ID, LABEL, format!(
                "{}: read_footer requested {stray} bytes from the DATA region ({}). Ranges requested: {}. The footer is at the end of the file precisely so that a reader can learn the schema without touching a single value.",
                fx.name, ranges_str(&rec.ranges()), ranges_str(&rec.ranges())));
        }
        // parse_footer on its own must agree with read_footer: two entry
        // points, one answer
        let footer_bytes = &fx.bytes[fx.footer_start as usize..fx.bytes.len() - 4];
        match parquet_reader::parse_footer(footer_bytes) {
            Ok(direct) => {
                if direct != meta {
                    return Check::fail(ID, LABEL, format!(
                        "{}: parse_footer over the footer's bytes disagrees with read_footer over the file — read_footer is supposed to do the framing (magic, length, bounds) and then hand exactly those bytes to parse_footer",
                        fx.name));
                }
            }
            Err(e) => {
                return Check::fail(ID, LABEL, format!(
                    "{}: parse_footer refused the {} valid footer bytes read_footer accepted, with {e:?}",
                    fx.name, footer_bytes.len()));
            }
        }
        files += 1;
        let bytes_read = rec.distinct_bytes();
        if bytes_read > (fx.bytes.len() as u64 - fx.footer_start) + 8 {
            return Check::fail(ID, LABEL, format!(
                "{}: read_footer touched {bytes_read} distinct bytes; the magic plus the footer region is {} bytes. Ranges: {}",
                fx.name, (fx.bytes.len() as u64 - fx.footer_start) + 4, ranges_str(&rec.ranges())));
        }
    }
    Check::pass(ID, LABEL, format!(
        "{files} generated KSPQ files parsed exactly — {cols_seen} column definitions, and every footer read touched only the magic and the footer region (no byte of the data region). KSPQ is a Parquet-SHAPED teaching format, not Parquet: what carries over is metadata-at-the-end, and the omissions are listed in your file's header.",
        ))
}

/// 2. rowgroup_metadata: chunk offsets, lengths and statistics, exact
///    against the writer's ledger — including chunks the writer recorded no
///    statistics for, which is `None` and not "min 0, max 0".
pub fn check_rowgroup_metadata() -> Check {
    const ID: &str = "rowgroup_metadata";
    const LABEL: &str = "row-group and column-chunk offsets, sizes and statistics read correctly";
    let mut rng = Rng(0x2011_04C4);

    let mut fixtures: Vec<Fixture> = edge_fixtures();
    for i in 0..12 {
        fixtures.push(make_fixture(&mut rng, i));
    }

    let (mut chunks, mut with_stats, mut without) = (0u64, 0u64, 0u64);
    let (mut rows_declared, mut chunk_bytes) = (0u64, 0u64);
    for fx in &fixtures {
        if let Err(msg) = audit(fx) {
            return Check::fail(ID, LABEL, msg);
        }
        let rec = Recording::new(&fx.bytes);
        let meta = match parquet_reader::read_footer(&rec) {
            Ok(m) => m,
            Err(e) => return Check::fail(ID, LABEL, format!("{}: read_footer failed with {e:?} — fix footer_parse first", fx.name, )),
        };
        if meta.row_groups.len() != fx.meta.row_groups.len() {
            return Check::fail(ID, LABEL, format!(
                "{}: {} row groups, want {} — num_row_groups is the u16 after the schema",
                fx.name, meta.row_groups.len(), fx.meta.row_groups.len()));
        }
        for (g, (got, want)) in meta.row_groups.iter().zip(&fx.meta.row_groups).enumerate() {
            if got.row_count != want.row_count {
                return Check::fail(ID, LABEL, format!(
                    "{}: row group {g} declares {} rows, want {} — row groups are not all the same size, and the last one usually is not (this file's last group holds {} rows)",
                    fx.name, got.row_count, want.row_count,
                    fx.meta.row_groups.last().map(|r| r.row_count).unwrap_or(0)));
            }
            if got.chunks.len() != want.chunks.len() {
                return Check::fail(ID, LABEL, format!(
                    "{}: row group {g} has {} column chunks, want {} — every row group carries exactly one chunk per schema column, in schema order. A short list means column {} has no byte range and cannot be projected at all.",
                    fx.name, got.chunks.len(), want.chunks.len(), got.chunks.len()));
            }
            for (c, (gc, wc)) in got.chunks.iter().zip(&want.chunks).enumerate() {
                if gc.offset != wc.offset {
                    return Check::fail(ID, LABEL, format!(
                        "{}: chunk ({g},{c}) offset {} , want {} — offsets are absolute from the start of the file, u64, and the chunk table is (offset, len, has_stats[, min, max, null_count]) per column. A drift of {} bytes suggests the optional statistics were not skipped for a chunk that has none.",
                        fx.name, gc.offset, wc.offset,
                        (gc.offset as i128 - wc.offset as i128).abs()));
                }
                if gc.len != wc.len {
                    return Check::fail(ID, LABEL, format!(
                        "{}: chunk ({g},{c}) length {}, want {} — this is the number of bytes a projection of column {c} pays for, and getting it wrong makes every cost estimate wrong",
                        fx.name, gc.len, wc.len));
                }
                match (gc.stats, wc.stats) {
                    (Some(g_s), Some(w_s)) => {
                        if g_s != w_s {
                            return Check::fail(ID, LABEL, format!(
                                "{}: chunk ({g},{c}) statistics {:?}, want {:?} — min and max are i64 over NON-NULL values, then null_count as a u32",
                                fx.name, g_s, w_s));
                        }
                        with_stats += 1;
                    }
                    (None, None) => without += 1,
                    (Some(g_s), None) => {
                        return Check::fail(ID, LABEL, format!(
                            "{}: chunk ({g},{c}) reports statistics {:?}, but has_stats is 0 for it — inventing bounds nobody wrote is how a planner proves a chunk impossible with a number that was never a bound (lab 02's false negative, arriving from the file format)",
                            fx.name, g_s));
                    }
                    (None, Some(w_s)) => {
                        return Check::fail(ID, LABEL, format!(
                            "{}: chunk ({g},{c}) reports no statistics, but the file records {:?} — has_stats is 1 here, and dropping the numbers costs every skip they would have proven",
                            fx.name, w_s));
                    }
                }
                chunks += 1;
                chunk_bytes += wc.len;
            }
            rows_declared += want.row_count as u64;
        }
        // the sum of the row groups is the file's row count: a consistency
        // check a reader can make before touching data
        let summed: u64 = meta.row_groups.iter().map(|r| r.row_count as u64).sum();
        if summed != meta.num_rows {
            return Check::fail(ID, LABEL, format!(
                "{}: the row groups sum to {summed} rows but the footer's num_rows is {} — one of the two was misread (the file itself is consistent; the harness wrote it)",
                fx.name, meta.num_rows));
        }
    }
    Check::pass(ID, LABEL, format!(
        "{chunks} column chunks across {} files exact — {with_stats} with statistics, {without} where the writer recorded none (read as None, not as zeroes). {rows_declared} rows and {chunk_bytes} chunk bytes accounted for from metadata alone, before a single value was read.",
        fixtures.len()))
}

/// 3. projection_reads_minimum: THE CHECK. A two-column projection must
///    touch ZERO bytes of the other columns' chunks. Graded from a
///    recording of every byte range requested — a count, never a time.
pub fn check_projection_reads_minimum() -> Check {
    const ID: &str = "projection_reads_minimum";
    const LABEL: &str = "a two-column projection touches only those column chunks (counted)";
    let mut rng = Rng(0x9805_04C3);

    let mut fixtures: Vec<Fixture> = edge_fixtures();
    for i in 0..12 {
        fixtures.push(make_fixture(&mut rng, i));
    }

    let (mut plans, mut projected_bytes, mut requested_bytes, mut file_bytes) = (0u64, 0u64, 0u64, 0u64);
    let (mut ranges, mut skipped_chunks, mut skipped_bytes) = (0u64, 0u64, 0u64);
    for fx in &fixtures {
        if let Err(msg) = audit(fx) {
            return Check::fail(ID, LABEL, msg);
        }
        let ncols = fx.ncols();
        let rec = Recording::new(&fx.bytes);
        let meta = match parquet_reader::read_footer(&rec) {
            Ok(m) => m,
            Err(e) => return Check::fail(ID, LABEL, format!("{}: read_footer failed with {e:?} — fix footer_parse first", fx.name)),
        };

        // a projection of NO columns reads no chunk bytes at all
        rec.reset();
        match parquet_reader::project(&rec, &meta, &[]) {
            Ok(out) => {
                if !out.is_empty() {
                    return Check::fail(ID, LABEL, format!(
                        "{}: projecting no columns returned {} columns — the answer to \"no columns, please\" is no columns",
                        fx.name, out.len()));
                }
                let touched = rec.bytes_requested();
                if touched > 0 {
                    return Check::fail(ID, LABEL, format!(
                        "{}: projecting NO columns still requested {touched} bytes ({}). SELECT count(*) is the same shape: the footer already told you how many rows there are, so there is nothing left to read.",
                        fx.name, ranges_str(&rec.ranges())));
                }
            }
            Err(e) => {
                return Check::fail(ID, LABEL, format!(
                    "{}: projecting an empty column list failed with {e:?} — it is a legal projection with an empty answer",
                    fx.name));
            }
        }

        // a column that does not exist must be refused BEFORE any data is
        // read: paying for three chunks and then failing is the worst of
        // both outcomes. Tested twice — alone, and AFTER a valid column,
        // which is the ordering a reader that validates lazily gets wrong.
        for plan in [vec![ncols + 3], vec![0, ncols + 3]] {
            rec.reset();
            match parquet_reader::project(&rec, &meta, &plan) {
                Ok(_) => {
                    return Check::fail(ID, LABEL, format!(
                        "{}: projecting {plan:?} from a {ncols}-column schema returned data instead of NoSuchColumn — column {} does not exist, and inventing one (or quietly substituting another) is the guess this lab refuses",
                        fx.name, ncols + 3));
                }
                Err(_) => {
                    let touched = rec.bytes_requested();
                    if touched > 0 {
                        return Check::fail(ID, LABEL, format!(
                            "{}: projecting {plan:?} correctly failed, but only after requesting {touched} bytes ({}). Validate the whole column list against the schema BEFORE reading anything: a query that is going to fail should cost nothing, and here it has already paid for column 0.",
                            fx.name, ranges_str(&rec.ranges())));
                    }
                }
            }
        }

        // every two-column projection (or the single column, in a
        // one-column file)
        let pairs: Vec<Vec<usize>> = if ncols == 1 {
            vec![vec![0]]
        } else {
            let mut v = Vec::new();
            for a in 0..ncols {
                for b in (a + 1)..ncols {
                    v.push(vec![a, b]);
                }
            }
            v
        };
        for cols in &pairs {
            rec.reset();
            let out = match parquet_reader::project(&rec, &meta, cols) {
                Ok(o) => o,
                Err(e) => {
                    return Check::fail(ID, LABEL, format!(
                        "{}: projecting columns {cols:?} failed with {e:?}",
                        fx.name));
                }
            };
            // correctness first: a projection that reads nothing and
            // returns nothing is not a pass
            if out.len() != cols.len() {
                return Check::fail(ID, LABEL, format!(
                    "{}: projecting {cols:?} returned {} columns, want {} — one output column per requested column, in the order requested",
                    fx.name, out.len(), cols.len()));
            }
            for (k, &c) in cols.iter().enumerate() {
                let want = fx.column(c);
                if out[k] != want {
                    return Check::fail(ID, LABEL, format!(
                        "{}: projected column {c} is {} ({} values), want {} ({} values) — values are concatenated across row groups in row-group order",
                        fx.name, vals_str(&out[k]), out[k].len(), vals_str(&want), want.len()));
                }
            }

            // THE ASSERTION: not one byte of any other column's chunks
            if let Some((g, c, fs, fe, overlap)) = forbidden_hits(&rec, fx, cols) {
                return Check::fail(ID, LABEL, format!(
                    "{}: projecting {cols:?} touched {overlap} byte(s) of chunk ({g},{c}), which lives at [{fs}, {fe}) and belongs to column {c} — a column this query did not ask for. Ranges you requested: {}. This is the whole promise of columnar storage, expressed as a count: reading a whole row group (or the whole file) and slicing it in memory is simpler to write, passes every other check in this suite, and costs the same as a row-store scan.",
                    fx.name, ranges_str(&rec.ranges())));
            }
            let stray = stray_bytes(&rec, fx, cols);
            if stray > 0 {
                return Check::fail(ID, LABEL, format!(
                    "{}: projecting {cols:?} requested {stray} byte(s) that are neither the magic, nor the footer region, nor a chunk of a projected column. Ranges: {}",
                    fx.name, ranges_str(&rec.ranges())));
            }

            let want_bytes = fx
                .meta
                .row_groups
                .iter()
                .flat_map(|rg| cols.iter().map(move |&c| rg.chunks[c].len))
                .sum::<u64>();
            let got_bytes = rec.bytes_requested();
            // a small allowance for framing: the projection may re-read the
            // footer if it wants to, but it may not read data twice
            let chunk_only: u64 = rec
                .ranges()
                .iter()
                .filter(|(o, _)| *o < fx.footer_start)
                .map(|(_, l)| *l)
                .sum();
            if chunk_only > want_bytes {
                return Check::fail(ID, LABEL, format!(
                    "{}: projecting {cols:?} requested {chunk_only} bytes from the data region for chunks totalling {want_bytes} bytes — the extra {} bytes are the same bytes fetched twice. One request per chunk. Ranges: {}",
                    fx.name, chunk_only - want_bytes, ranges_str(&rec.ranges())));
            }
            plans += 1;
            projected_bytes += want_bytes;
            requested_bytes += got_bytes;
            ranges += rec.ranges().len() as u64;
            file_bytes += fx.bytes.len() as u64;
            let others: Vec<&ChunkMeta> = fx
                .meta
                .row_groups
                .iter()
                .flat_map(|rg| rg.chunks.iter().enumerate().filter(|(c, _)| !cols.contains(c)).map(|(_, ch)| ch))
                .collect();
            skipped_chunks += others.len() as u64;
            skipped_bytes += others.iter().map(|c| c.len).sum::<u64>();
        }
    }
    Check::pass(ID, LABEL, format!(
        "{plans} projections over {} files: {requested_bytes} bytes requested in {ranges} ranges, against {file_bytes} bytes of file — {}. The projected chunks are {projected_bytes} bytes; {skipped_chunks} chunks totalling {skipped_bytes} bytes were never touched, not one byte. Empty projections requested nothing at all, and a projection naming a missing column failed before paying for anything.",
        fixtures.len(),
        percent(requested_bytes, file_bytes)))
}

/// 4. rejects_malformed: sixteen broken files. Each one must produce an
///    error — not a guess, not a partial answer, and not a panic (a panic
///    traps the wasm module, and "not implemented yet" is not a diagnosis).
pub fn check_rejects_malformed() -> Check {
    const ID: &str = "rejects_malformed";
    const LABEL: &str = "truncated, wrong-magic and inconsistent-length files are rejected, not guessed at";
    let mut rng = Rng(0xBAD_F11E);

    let base = make_fixture(&mut rng, 4);
    if let Err(msg) = audit(&base) {
        return Check::fail(ID, LABEL, msg);
    }
    // the base file must itself be readable, or "it errored" proves nothing
    {
        let rec = Recording::new(&base.bytes);
        let meta = match parquet_reader::read_footer(&rec) {
            Ok(m) => m,
            Err(e) => {
                return Check::fail(ID, LABEL, format!(
                    "the VALID file these malformed variants are derived from was refused with {e:?} — a reader that rejects everything passes this check for the wrong reason, so it is tested first",
                    ));
            }
        };
        let cols: Vec<usize> = (0..base.ncols()).collect();
        if let Err(e) = parquet_reader::project(&rec, &meta, &cols) {
            return Check::fail(ID, LABEL, format!("the valid base file could not be projected: {e:?}"));
        }
    }

    let broken = broken_files(&base);
    let (mut footer_rejects, mut data_rejects) = (0u64, 0u64);
    for b in &broken {
        let rec = Recording::new(&b.bytes);
        match parquet_reader::read_footer(&rec) {
            Err(_) => {
                if !b.footer_must_fail {
                    // erroring early is acceptable — the file IS broken —
                    // but note it so the message stays honest
                    data_rejects += 1;
                    continue;
                }
                footer_rejects += 1;
            }
            Ok(meta) => {
                if b.footer_must_fail {
                    return Check::fail(ID, LABEL, format!(
                        "{}: read_footer ACCEPTED this file and returned {} columns / {} row groups / num_rows {}. {}. A reader that guesses here produces plausible garbage, and plausible garbage becomes a number in a report somebody makes a decision on. Refuse loudly instead.",
                        b.name, meta.schema.len(), meta.row_groups.len(), meta.num_rows, b.why));
                }
                // the footer is fine; the failure must arrive when the data
                // is read
                let cols: Vec<usize> = (0..meta.schema.len()).collect();
                match parquet_reader::project(&rec, &meta, &cols) {
                    Ok(out) => {
                        return Check::fail(ID, LABEL, format!(
                            "{}: the footer parsed (correctly — it is well-formed) and then project() SUCCEEDED, returning {} columns of {} values. {}.",
                            b.name, out.len(),
                            out.first().map(|c| c.len()).unwrap_or(0), b.why));
                    }
                    Err(_) => data_rejects += 1,
                }
                // and read_chunk on the offending chunk must refuse too
                if let Some(chunk) = meta.row_groups.first().and_then(|rg| rg.chunks.first()) {
                    if let Ok(vals) = parquet_reader::read_chunk(&rec, chunk) {
                        return Check::fail(ID, LABEL, format!(
                            "{}: read_chunk returned {} values for a chunk at [{}, {}) in a {}-byte file. {}. Bounds-check offset + len with CHECKED arithmetic against src.len() before you read.",
                            b.name, vals.len(), chunk.offset, chunk.offset.wrapping_add(chunk.len),
                            b.bytes.len(), b.why));
                    }
                }
            }
        }
    }

    // a well-formed file read with a hostile chunk descriptor: the reader
    // must not trust a ChunkMeta it did not get from a footer either
    let rec = Recording::new(&base.bytes);
    let hostile = [
        ChunkMeta { offset: base.bytes.len() as u64, len: 8, stats: None },
        ChunkMeta { offset: u64::MAX - 4, len: 8, stats: None },
        ChunkMeta { offset: 0, len: u64::MAX, stats: None },
        ChunkMeta { offset: 4, len: 3, stats: None },
        ChunkMeta { offset: 4, len: 0, stats: None },
    ];
    for chunk in &hostile {
        if let Ok(vals) = parquet_reader::read_chunk(&rec, chunk) {
            return Check::fail(ID, LABEL, format!(
                "read_chunk accepted {:?} against a {}-byte file and returned {} values — offset + len must be checked (with checked_add, because it overflows here) against src.len(), and a payload shorter than its own u32 header is a BadChunk",
                chunk, base.bytes.len(), vals.len()));
        }
    }

    Check::pass(ID, LABEL, format!(
        "{} malformed files all refused — {footer_rejects} at the footer (empty, 3-byte and 7-byte files, wrong magic, a 40-byte truncation, footer_len longer than the file, footer_len = u32::MAX, footer_len = 0, a 5-byte-short footer, version 7, an unknown type tag, inflated column and row-group counts) and {data_rejects} when the data was followed (a chunk offset past the end, a length that overflows, a value count the chunk cannot hold). {} hostile chunk descriptors refused as well, and the valid file this family is derived from still reads correctly.",
        broken.len(), hostile.len()))
}

/// 5. storm: 400 seeded read plans across seeded fixtures, every one of
///    them compared against an independent reference reader — with the
///    projection accounting re-checked on each plan.
pub fn check_storm() -> Check {
    const ID: &str = "storm";
    const LABEL: &str = "400 seeded read plans across fixtures vs a reference reader";
    let mut rng = Rng(0x5EED_0404);
    const PLANS: usize = 400;

    let mut fixtures: Vec<Fixture> = edge_fixtures();
    for i in 0..20 {
        fixtures.push(make_fixture(&mut rng, i));
    }
    for fx in &fixtures {
        if let Err(msg) = audit(fx) {
            return Check::fail(ID, LABEL, msg);
        }
    }

    let mut plan_kinds: BTreeMap<&'static str, usize> = BTreeMap::new();
    let (mut done, mut requested, mut projected, mut whole_file) = (0usize, 0u64, 0u64, 0u64);
    let (mut ranges, mut values_read, mut untouched) = (0u64, 0u64, 0u64);
    let mut i = 0usize;
    while done < PLANS {
        let fx = &fixtures[i % fixtures.len()];
        let ncols = fx.ncols();
        let rec = Recording::new(&fx.bytes);
        let meta = match parquet_reader::read_footer(&rec) {
            Ok(m) => m,
            Err(e) => return Check::fail(ID, LABEL, format!("{}: read_footer failed with {e:?}", fx.name)),
        };
        let want_meta = ref_read_footer(&fx.bytes).expect("audited above");
        if meta != want_meta {
            return Check::fail(ID, LABEL, format!(
                "{}: your footer differs from the reference reader's — fix footer_parse and rowgroup_metadata first",
                fx.name));
        }

        // a read plan: which columns, in which order, sometimes repeated
        let (kind, cols): (&'static str, Vec<usize>) = match i % 6 {
            0 => ("one column", vec![rng.below(ncols)]),
            1 => {
                let a = rng.below(ncols);
                let b = rng.below(ncols);
                ("two columns", if a == b { vec![a] } else { vec![a, b] })
            }
            2 => ("every column", (0..ncols).collect()),
            3 => ("reversed order", (0..ncols).rev().collect()),
            4 => {
                let a = rng.below(ncols);
                ("the same column twice", vec![a, a])
            }
            _ => ("a random subset", (0..ncols).filter(|_| rng.below(2) == 0).collect()),
        };
        *plan_kinds.entry(kind).or_insert(0) += 1;

        rec.reset();
        let got = match parquet_reader::project(&rec, &meta, &cols) {
            Ok(o) => o,
            Err(e) => {
                return Check::fail(ID, LABEL, format!(
                    "{}: projecting {cols:?} ({kind}) failed with {e:?} — every column index here is in range",
                    fx.name));
            }
        };
        let want = match ref_project(&fx.bytes, &want_meta, &cols) {
            Ok(w) => w,
            Err(e) => {
                return Check::fail(ID, LABEL, format!(
                    "HARNESS BUG: the reference reader failed on {} with {cols:?}: {e} — please report this",
                    fx.name));
            }
        };
        if got.len() != want.len() {
            return Check::fail(ID, LABEL, format!(
                "{}: projecting {cols:?} ({kind}) returned {} columns, want {} — one per entry of the request, including repeats",
                fx.name, got.len(), want.len()));
        }
        for (k, (g, w)) in got.iter().zip(&want).enumerate() {
            if g != w {
                let first = (0..g.len().max(w.len())).find(|&r| g.get(r) != w.get(r)).unwrap_or(0);
                return Check::fail(ID, LABEL, format!(
                    "{}: projecting {cols:?} ({kind}), output column {k} (schema column {}) differs from the reference at value {first}: {:?} vs {:?}. Yours has {} values, the reference has {}. Remember the null bitmap decides nullity — a null row stores the eight zero bytes of 0, so inferring nulls from the value turns every real zero into a NULL.",
                    fx.name, cols[k], g.get(first), w.get(first), g.len(), w.len()));
            }
            values_read += g.len() as u64;
        }
        if let Some((g2, c2, fs, fe, overlap)) = forbidden_hits(&rec, fx, &cols) {
            return Check::fail(ID, LABEL, format!(
                "{}: projecting {cols:?} ({kind}) touched {overlap} byte(s) of chunk ({g2},{c2}) at [{fs}, {fe}), which belongs to a column the plan did not name. Ranges: {}",
                fx.name, ranges_str(&rec.ranges())));
        }
        let stray = stray_bytes(&rec, fx, &cols);
        if stray > 0 {
            return Check::fail(ID, LABEL, format!(
                "{}: projecting {cols:?} ({kind}) requested {stray} stray byte(s) — outside the magic, the footer region and the projected chunks. Ranges: {}",
                fx.name, ranges_str(&rec.ranges())));
        }

        // and one direct read_chunk per plan, against the ledger
        if !fx.meta.row_groups.is_empty() {
            let g = rng.below(fx.meta.row_groups.len());
            let c = rng.below(ncols);
            let chunk = &meta.row_groups[g].chunks[c];
            match parquet_reader::read_chunk(&rec, chunk) {
                Ok(vals) => {
                    if vals != fx.values[g][c] {
                        return Check::fail(ID, LABEL, format!(
                            "{}: read_chunk({g},{c}) gave {} ({} values), the writer wrote {} ({} values)",
                            fx.name, vals_str(&vals), vals.len(),
                            vals_str(&fx.values[g][c]), fx.values[g][c].len()));
                    }
                }
                Err(e) => {
                    return Check::fail(ID, LABEL, format!(
                        "{}: read_chunk on the valid chunk ({g},{c}) at [{}, {}) failed with {e:?}",
                        fx.name, chunk.offset, chunk.offset + chunk.len));
                }
            }
        }

        requested += rec.bytes_requested();
        ranges += rec.ranges().len() as u64;
        projected += fx
            .meta
            .row_groups
            .iter()
            .flat_map(|rg| cols.iter().map(move |&c| rg.chunks[c].len))
            .sum::<u64>();
        whole_file += fx.bytes.len() as u64;
        untouched += fx
            .meta
            .row_groups
            .iter()
            .flat_map(|rg| rg.chunks.iter().enumerate().filter(|(c, _)| !cols.contains(c)).map(|(_, ch)| ch.len))
            .sum::<u64>();
        done += 1;
        i += 1;
    }

    let mix: Vec<String> = plan_kinds.iter().map(|(k, v)| format!("{k} {v}")).collect();
    Check::pass(ID, LABEL, format!(
        "{done} read plans over {} fixtures agree with an independent reference reader value for value — {values_read} values decoded. {requested} bytes requested in {ranges} ranges against {whole_file} bytes of file ({}); the plans' own chunks are {projected} bytes and the {untouched} bytes belonging to unprojected columns were never touched. Plan mix: {}. (KSPQ, the Parquet-shaped teaching format — pages, Thrift, levels and codecs are named as omissions in your file's header.)",
        fixtures.len(), percent(requested, whole_file), mix.join(", ")))
}

/// The full suite, in grading order.
pub fn self_checks() -> Vec<Check> {
    vec![
        check_footer_parse(),
        check_rowgroup_metadata(),
        check_projection_reads_minimum(),
        check_rejects_malformed(),
        check_storm(),
    ]
}

