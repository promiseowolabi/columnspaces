/* --------------------------- determinism ---------------------------- */

/// xorshift64* — the same files and the same read plans on every machine,
/// every run, in both wasm and native.
struct Rng(u64);

impl Rng {
    fn next(&mut self) -> u64 {
        let mut x = self.0;
        x ^= x >> 12;
        x ^= x << 25;
        x ^= x >> 27;
        self.0 = x;
        x.wrapping_mul(0x2545_F491_4F6C_DD1D)
    }
    fn below(&mut self, n: usize) -> usize {
        if n == 0 { 0 } else { (self.next() % n as u64) as usize }
    }
}

/* ------------------------------ the writer -------------------------- */

const MAGIC: [u8; 4] = *b"KSPQ";
const VERSION: u16 = 1;

fn put_u16(out: &mut Vec<u8>, v: u16) {
    out.extend_from_slice(&v.to_le_bytes());
}
fn put_u32(out: &mut Vec<u8>, v: u32) {
    out.extend_from_slice(&v.to_le_bytes());
}
fn put_u64(out: &mut Vec<u8>, v: u64) {
    out.extend_from_slice(&v.to_le_bytes());
}
fn put_i64(out: &mut Vec<u8>, v: i64) {
    out.extend_from_slice(&v.to_le_bytes());
}

/// The payload of one column chunk: `u32 n`, a null bitmap, then `n` i64s.
/// A null row stores 0, which is why the bitmap and not the value decides
/// nullity — and why a reader that infers nulls from zeros turns every
/// legitimate zero in the file into a NULL.
fn encode_chunk(values: &[Option<i64>]) -> Vec<u8> {
    let n = values.len();
    let mut out = Vec::with_capacity(4 + (n + 7) / 8 + n * 8);
    put_u32(&mut out, n as u32);
    let mut bitmap = vec![0u8; (n + 7) / 8];
    for (i, v) in values.iter().enumerate() {
        if v.is_none() {
            bitmap[i / 8] |= 1 << (i % 8);
        }
    }
    out.extend_from_slice(&bitmap);
    for v in values {
        put_i64(&mut out, v.unwrap_or(0));
    }
    out
}

/// The zone map a writer records, over non-null values. `None` when the
/// chunk holds no non-null value: there is nothing to bound.
fn chunk_stats(values: &[Option<i64>]) -> Option<ChunkStats> {
    let live: Vec<i64> = values.iter().filter_map(|v| *v).collect();
    let null_count = (values.len() - live.len()) as u32;
    Some(ChunkStats { min: *live.iter().min()?, max: *live.iter().max()?, null_count })
}

/// A generated file, plus the ledger that makes it gradeable.
struct Fixture {
    name: String,
    bytes: Vec<u8>,
    /// GROUND TRUTH metadata, as written.
    meta: FileMeta,
    /// GROUND TRUTH values: `[row_group][column][row]`.
    values: Vec<Vec<Vec<Option<i64>>>>,
    /// Where the footer begins — the whole tail region is legal to read.
    footer_start: u64,
}

impl Fixture {
    /// The full column, concatenated across row groups: what `project`
    /// must return for that column.
    fn column(&self, c: usize) -> Vec<Option<i64>> {
        self.values.iter().flat_map(|rg| rg[c].iter().copied()).collect()
    }

    fn ncols(&self) -> usize {
        self.meta.schema.len()
    }

    /// The byte ranges a projection is allowed to touch: the magic, the
    /// whole footer region, and the named columns' chunks. Everything else
    /// in the file is forbidden — including other columns' chunks, which is
    /// the point of the check.
    fn allowed(&self, columns: &[usize]) -> Vec<(u64, u64)> {
        let mut out = vec![(0u64, 4u64), (self.footer_start, self.bytes.len() as u64)];
        for rg in &self.meta.row_groups {
            for &c in columns {
                if let Some(ch) = rg.chunks.get(c) {
                    out.push((ch.offset, ch.offset + ch.len));
                }
            }
        }
        out
    }

    /// Bytes of the chunks a projection must NOT touch, as ranges.
    fn forbidden(&self, columns: &[usize]) -> Vec<(usize, usize, u64, u64)> {
        let mut out = Vec::new();
        for (g, rg) in self.meta.row_groups.iter().enumerate() {
            for (c, ch) in rg.chunks.iter().enumerate() {
                if !columns.contains(&c) {
                    out.push((g, c, ch.offset, ch.offset + ch.len));
                }
            }
        }
        out
    }
}

/// Write a KSPQ file from `[row_group][column][row]` values and a schema.
/// Data first (row-group-major), then the footer, then the footer length.
fn write_file(name: String, schema: Vec<ColumnMeta>, values: Vec<Vec<Vec<Option<i64>>>>, stats: bool) -> Fixture {
    let ncols = schema.len();
    let mut bytes = Vec::new();
    bytes.extend_from_slice(&MAGIC);
    let mut row_groups: Vec<RowGroupMeta> = Vec::new();
    let mut num_rows = 0u64;
    for rg in &values {
        let row_count = rg.first().map(|c| c.len()).unwrap_or(0);
        num_rows += row_count as u64;
        let mut chunks = Vec::with_capacity(ncols);
        for col in rg.iter() {
            let payload = encode_chunk(col);
            let offset = bytes.len() as u64;
            bytes.extend_from_slice(&payload);
            chunks.push(ChunkMeta {
                offset,
                len: payload.len() as u64,
                stats: if stats { chunk_stats(col) } else { None },
            });
        }
        row_groups.push(RowGroupMeta { row_count: row_count as u32, chunks });
    }

    let meta = FileMeta { version: VERSION, num_rows, schema, row_groups };
    let footer = encode_footer(&meta);
    let footer_start = bytes.len() as u64;
    bytes.extend_from_slice(&footer);
    put_u32(&mut bytes, footer.len() as u32);
    Fixture { name, bytes, meta, values, footer_start }
}

fn encode_footer(meta: &FileMeta) -> Vec<u8> {
    let mut f = Vec::new();
    put_u16(&mut f, meta.version);
    put_u64(&mut f, meta.num_rows);
    put_u16(&mut f, meta.schema.len() as u16);
    for col in &meta.schema {
        f.push(col.name.len() as u8);
        f.extend_from_slice(col.name.as_bytes());
        f.push(match col.logical {
            Logical::Int64 => 1,
            Logical::Timestamp => 2,
            Logical::Bool => 3,
        });
    }
    put_u16(&mut f, meta.row_groups.len() as u16);
    for rg in &meta.row_groups {
        put_u32(&mut f, rg.row_count);
        for ch in &rg.chunks {
            put_u64(&mut f, ch.offset);
            put_u64(&mut f, ch.len);
            match ch.stats {
                None => f.push(0),
                Some(s) => {
                    f.push(1);
                    put_i64(&mut f, s.min);
                    put_i64(&mut f, s.max);
                    put_u32(&mut f, s.null_count);
                }
            }
        }
    }
    f
}

/* -------------------------- reference reader ------------------------ */
/* A second implementation, used by storm and audited against the writer's  */
/* ledger on every fixture.                                                */

struct RefCursor<'a> {
    b: &'a [u8],
    p: usize,
}

impl<'a> RefCursor<'a> {
    fn new(b: &'a [u8]) -> RefCursor<'a> {
        RefCursor { b, p: 0 }
    }
    fn take(&mut self, n: usize) -> Result<&'a [u8], String> {
        if self.b.len() - self.p.min(self.b.len()) < n {
            return Err(format!("truncated: need {n}, have {}", self.b.len().saturating_sub(self.p)));
        }
        let o = &self.b[self.p..self.p + n];
        self.p += n;
        Ok(o)
    }
    fn u8(&mut self) -> Result<u8, String> {
        Ok(self.take(1)?[0])
    }
    fn u16(&mut self) -> Result<u16, String> {
        let b = self.take(2)?;
        Ok(u16::from_le_bytes([b[0], b[1]]))
    }
    fn u32(&mut self) -> Result<u32, String> {
        let b = self.take(4)?;
        Ok(u32::from_le_bytes([b[0], b[1], b[2], b[3]]))
    }
    fn u64(&mut self) -> Result<u64, String> {
        let b = self.take(8)?;
        let mut a = [0u8; 8];
        a.copy_from_slice(b);
        Ok(u64::from_le_bytes(a))
    }
}

fn ref_read_footer(bytes: &[u8]) -> Result<FileMeta, String> {
    if (bytes.len() as u64) < 8 {
        return Err("too short".into());
    }
    if bytes[..4] != MAGIC {
        return Err("bad magic".into());
    }
    let len_at = bytes.len() - 4;
    let footer_len = u32::from_le_bytes([bytes[len_at], bytes[len_at + 1], bytes[len_at + 2], bytes[len_at + 3]]) as u64;
    if 4 + footer_len + 4 > bytes.len() as u64 {
        return Err("footer_len does not fit".into());
    }
    let start = bytes.len() as u64 - 4 - footer_len;
    let f = &bytes[start as usize..len_at];
    let mut c = RefCursor::new(f);
    let version = c.u16()?;
    if version != VERSION {
        return Err(format!("bad version {version}"));
    }
    let num_rows = c.u64()?;
    let ncols = c.u16()? as usize;
    let mut schema = Vec::with_capacity(ncols);
    for _ in 0..ncols {
        let nlen = c.u8()? as usize;
        let name = String::from_utf8(c.take(nlen)?.to_vec()).map_err(|_| "bad name".to_string())?;
        let logical = match c.u8()? {
            1 => Logical::Int64,
            2 => Logical::Timestamp,
            3 => Logical::Bool,
            t => return Err(format!("unknown type {t}")),
        };
        schema.push(ColumnMeta { name, logical });
    }
    let ngroups = c.u16()? as usize;
    let mut row_groups = Vec::with_capacity(ngroups);
    for _ in 0..ngroups {
        let row_count = c.u32()?;
        let mut chunks = Vec::with_capacity(ncols);
        for _ in 0..ncols {
            let offset = c.u64()?;
            let len = c.u64()?;
            let stats = match c.u8()? {
                0 => None,
                1 => {
                    let min = c.u64()? as i64;
                    let max = c.u64()? as i64;
                    let null_count = c.u32()?;
                    Some(ChunkStats { min, max, null_count })
                }
                other => return Err(format!("bad has_stats {other}")),
            };
            chunks.push(ChunkMeta { offset, len, stats });
        }
        row_groups.push(RowGroupMeta { row_count, chunks });
    }
    Ok(FileMeta { version, num_rows, schema, row_groups })
}

fn ref_read_chunk(bytes: &[u8], chunk: &ChunkMeta) -> Result<Vec<Option<i64>>, String> {
    let end = chunk.offset.checked_add(chunk.len).ok_or("offset+len overflows")?;
    if end > bytes.len() as u64 {
        return Err("chunk out of bounds".into());
    }
    let payload = &bytes[chunk.offset as usize..end as usize];
    let mut c = RefCursor::new(payload);
    let n = c.u32()? as usize;
    let bitmap = c.take((n + 7) / 8)?.to_vec();
    let mut out = Vec::with_capacity(n);
    for i in 0..n {
        let raw = c.u64()? as i64;
        let null = bitmap[i / 8] & (1 << (i % 8)) != 0;
        out.push(if null { None } else { Some(raw) });
    }
    Ok(out)
}

fn ref_project(bytes: &[u8], meta: &FileMeta, columns: &[usize]) -> Result<Vec<Vec<Option<i64>>>, String> {
    for &c in columns {
        if c >= meta.schema.len() {
            return Err(format!("no such column {c}"));
        }
    }
    let mut out = Vec::with_capacity(columns.len());
    for &c in columns {
        let mut col = Vec::new();
        for rg in &meta.row_groups {
            col.extend(ref_read_chunk(bytes, &rg.chunks[c])?);
        }
        out.push(col);
    }
    Ok(out)
}

/* ------------------------ the instrumented source ------------------- */

/// The grading instrument: a `Source` that answers honestly and remembers
/// every question. `RefCell` because wasm is single threaded and a lock
/// would be theatre.
struct Recording<'a> {
    bytes: &'a [u8],
    reads: RefCell<Vec<(u64, u64)>>,
}

impl<'a> Recording<'a> {
    fn new(bytes: &'a [u8]) -> Recording<'a> {
        Recording { bytes, reads: RefCell::new(Vec::new()) }
    }
    fn reset(&self) {
        self.reads.borrow_mut().clear();
    }
    fn ranges(&self) -> Vec<(u64, u64)> {
        self.reads.borrow().clone()
    }
    fn bytes_requested(&self) -> u64 {
        self.reads.borrow().iter().map(|(_, l)| *l).sum()
    }
    /// Distinct bytes of the file that were touched at least once — a
    /// re-read of the same range is a second request but not a second byte.
    fn distinct_bytes(&self) -> u64 {
        let mut marks = vec![false; self.bytes.len()];
        for (o, l) in self.reads.borrow().iter() {
            for i in *o..(*o + *l).min(self.bytes.len() as u64) {
                marks[i as usize] = true;
            }
        }
        marks.iter().filter(|m| **m).count() as u64
    }
}

impl Source for Recording<'_> {
    fn len(&self) -> u64 {
        self.bytes.len() as u64
    }
    fn read(&self, offset: u64, len: u64) -> Result<Vec<u8>, Error> {
        // recorded FIRST: an out-of-range request is still a request, and a
        // reader that gropes past the end should be visible
        self.reads.borrow_mut().push((offset, len));
        let end = match offset.checked_add(len) {
            Some(e) => e,
            None => return Err(Error::OutOfBounds { offset, len, file_len: self.bytes.len() as u64 }),
        };
        if end > self.bytes.len() as u64 {
            return Err(Error::OutOfBounds { offset, len, file_len: self.bytes.len() as u64 });
        }
        Ok(self.bytes[offset as usize..end as usize].to_vec())
    }
}

/// Bytes the student requested that fall inside a forbidden range, with the
/// first offender named.
fn forbidden_hits(rec: &Recording, fx: &Fixture, columns: &[usize]) -> Option<(usize, usize, u64, u64, u64)> {
    let forbidden = fx.forbidden(columns);
    for (o, l) in rec.ranges() {
        let (rs, re) = (o, o.saturating_add(l));
        for (g, c, fs, fe) in &forbidden {
            let lo = rs.max(*fs);
            let hi = re.min(*fe);
            if lo < hi {
                return Some((*g, *c, *fs, *fe, hi - lo));
            }
        }
    }
    None
}

/// Requested bytes outside the union of allowed ranges — padding, gaps, or
/// anything else nobody asked for. (In a KSPQ file there is no padding, so
/// this only fires on genuinely stray reads.)
fn stray_bytes(rec: &Recording, fx: &Fixture, columns: &[usize]) -> u64 {
    let allowed = fx.allowed(columns);
    let mut stray = 0u64;
    for (o, l) in rec.ranges() {
        for i in o..o.saturating_add(l) {
            if !allowed.iter().any(|(s, e)| i >= *s && i < *e) {
                stray += 1;
            }
        }
    }
    stray
}

/* ---------------------------- formatting ---------------------------- */

fn percent(part: u64, whole: u64) -> String {
    if whole == 0 {
        return "n/a".to_string();
    }
    let tenths = part * 1000 / whole;
    format!("{}.{}%", tenths / 10, tenths % 10)
}

fn vals_str(vs: &[Option<i64>]) -> String {
    if vs.len() <= 8 {
        format!("{vs:?}")
    } else {
        format!("[{:?}, … {} more]", &vs[..6], vs.len() - 6)
    }
}

fn ranges_str(rs: &[(u64, u64)]) -> String {
    let shown: Vec<String> = rs.iter().take(8).map(|(o, l)| format!("[{o}, {})", o + l)).collect();
    if rs.len() > 8 {
        format!("{} … and {} more", shown.join(" "), rs.len() - 8)
    } else if shown.is_empty() {
        "none".to_string()
    } else {
        shown.join(" ")
    }
}

/* --------------------------- column shapes -------------------------- */

fn col_values(rng: &mut Rng, n: usize, kind: usize) -> Vec<Option<i64>> {
    match kind % 7 {
        // monotone timestamps
        0 => {
            let mut t = 1_700_000_000_000i64 + rng.below(1 << 20) as i64;
            (0..n)
                .map(|_| {
                    t = t.wrapping_add(1 + rng.below(97) as i64);
                    Some(t)
                })
                .collect()
        }
        // small ids with 1-in-7 nulls
        1 => (0..n)
            .map(|_| if rng.below(7) == 0 { None } else { Some(rng.below(500) as i64) })
            .collect(),
        // all null: the chunk with no statistics to record
        2 => vec![None; n],
        // zeros and nulls together — the case a reader that infers nullity
        // from the value gets wrong
        3 => (0..n).map(|i| if i % 3 == 0 { None } else { Some(0) }).collect(),
        // booleans
        4 => (0..n).map(|_| Some(rng.below(2) as i64)).collect(),
        // i64 edges
        5 => (0..n)
            .map(|_| match rng.below(5) {
                0 => Some(i64::MIN),
                1 => Some(i64::MAX),
                2 => None,
                3 => Some(0),
                _ => Some(rng.next() as i64),
            })
            .collect(),
        // negative and large
        _ => (0..n).map(|_| Some(-(rng.below(1 << 30) as i64))).collect(),
    }
}

fn logical_for(kind: usize) -> Logical {
    match kind % 7 {
        0 => Logical::Timestamp,
        4 => Logical::Bool,
        _ => Logical::Int64,
    }
}

/// Ten file shapes: different column counts, row-group counts, partial
/// final row groups, all-null columns, statistics present or absent, and
/// the degenerate cases (one row, zero rows, one row group).
fn make_fixture(rng: &mut Rng, i: usize) -> Fixture {
    let ncols = [1usize, 2, 3, 4, 5, 6][i % 6];
    let ngroups = [1usize, 2, 3, 4, 5][i % 5];
    let rows_per_group = [1usize, 7, 32, 64, 100, 257][i % 6];
    // the final row group is deliberately partial in most shapes
    let last = if i % 3 == 0 { rows_per_group } else { 1 + rng.below(rows_per_group) };
    let stats = i % 4 != 3;
    let kinds: Vec<usize> = (0..ncols).map(|c| (i + c * 3) % 7).collect();
    let schema: Vec<ColumnMeta> = kinds
        .iter()
        .enumerate()
        .map(|(c, &k)| ColumnMeta { name: format!("col_{c}"), logical: logical_for(k) })
        .collect();
    let mut values = Vec::with_capacity(ngroups);
    for g in 0..ngroups {
        let rows = if g + 1 == ngroups { last } else { rows_per_group };
        values.push(kinds.iter().map(|&k| col_values(rng, rows, k)).collect());
    }
    let name = format!(
        "{ncols} cols × {ngroups} row groups of {rows_per_group} (last {last}){}",
        if stats { "" } else { ", no statistics recorded" }
    );
    write_file(name, schema, values, stats)
}

/// The awkward shapes, by hand: a file with no row groups at all, a file
/// with a zero-row row group, and a one-value file.
fn edge_fixtures() -> Vec<Fixture> {
    let int = |name: &str| ColumnMeta { name: name.to_string(), logical: Logical::Int64 };
    vec![
        write_file("no row groups (an empty table)".into(), vec![int("a"), int("b")], vec![], true),
        write_file("one row group of zero rows".into(), vec![int("a"), int("b")], vec![vec![vec![], vec![]]], true),
        write_file("one row, one column".into(), vec![int("only")], vec![vec![vec![Some(42)]]], true),
        write_file(
            "one column, all null (no statistics possible)".into(),
            vec![int("nothing")],
            vec![vec![vec![None, None, None]]],
            true,
        ),
        write_file(
            "16 columns, 2 row groups — projection has plenty to avoid".into(),
            (0..16).map(|c| int(&format!("c{c}"))).collect(),
            (0..2)
                .map(|g| (0..16).map(|c| (0..40).map(|r| Some((g * 1000 + c * 40 + r) as i64)).collect()).collect())
                .collect(),
            true,
        ),
    ]
}

/* --------------------------- harness audit -------------------------- */

/// The harness auditing itself: the reference reader must recover exactly
/// what the writer wrote, and the writer's declared chunk ranges must be
/// inside the file and not overlap the footer. If any of this fails, the
/// fixture is unsound and grading a student against it would be worse than
/// grading nothing.
fn audit(fx: &Fixture) -> Result<(), String> {
    let meta = ref_read_footer(&fx.bytes)
        .map_err(|e| format!("HARNESS BUG: the reference reader cannot read the fixture it just wrote ({}): {e} — please report this", fx.name))?;
    if meta != fx.meta {
        return Err(format!(
            "HARNESS BUG: reference footer != written footer for {} — please report this",
            fx.name));
    }
    for (g, rg) in fx.meta.row_groups.iter().enumerate() {
        if rg.chunks.len() != fx.meta.schema.len() {
            return Err(format!("HARNESS BUG: row group {g} of {} has the wrong chunk count — please report this", fx.name));
        }
        for (c, ch) in rg.chunks.iter().enumerate() {
            if ch.offset + ch.len > fx.footer_start {
                return Err(format!(
                    "HARNESS BUG: chunk ({g},{c}) of {} overlaps the footer — please report this",
                    fx.name));
            }
            let got = ref_read_chunk(&fx.bytes, ch)
                .map_err(|e| format!("HARNESS BUG: reference chunk read failed on {} ({g},{c}): {e} — please report this", fx.name))?;
            if got != fx.values[g][c] {
                return Err(format!(
                    "HARNESS BUG: reference chunk ({g},{c}) of {} decodes to something other than what was written — please report this",
                    fx.name));
            }
        }
    }
    Ok(())
}

/* --------------------------- malformed files ------------------------ */

/// A malformed file, the reason it is malformed, and which of the student's
/// entry points must refuse it.
struct Broken {
    name: &'static str,
    why: &'static str,
    bytes: Vec<u8>,
    /// true: `read_footer` must fail. false: the footer is fine and the
    /// failure must appear when the data is read.
    footer_must_fail: bool,
}

fn set_u32(bytes: &mut [u8], at: usize, v: u32) {
    bytes[at..at + 4].copy_from_slice(&v.to_le_bytes());
}
fn set_u64(bytes: &mut [u8], at: usize, v: u64) {
    bytes[at..at + 8].copy_from_slice(&v.to_le_bytes());
}

/// Where the footer's per-row-group chunk table starts, for a fixture whose
/// shape the harness knows: version(2) + num_rows(8) + num_columns(2) +
/// per-column (1 + name + 1) + num_row_groups(2) + row_count(4).
fn first_chunk_field(fx: &Fixture) -> usize {
    let mut p = fx.footer_start as usize + 2 + 8 + 2;
    for col in &fx.meta.schema {
        p += 1 + col.name.len() + 1;
    }
    p + 2 + 4
}

